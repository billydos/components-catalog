// Package catalog обеспечивает доступ к каталожным таблицам (параметры,
// атрибуты, условия, единицы, группы, именованные правила, системы
// обозначений, реестр семейств) и содержит движок валидации значений
// по правилам из БД.
//
// Состав пакета (план работ, этап 2):
//   - Snapshot — иммутабельный снимок каталога; Store — транспорт чтения
//     определений (реализация над БД — internal/storage, этап 3);
//     Cache — кэш с проверкой catalog_revision на каждом обращении:
//     при изменении снимок атомарно заменяется целиком (docs/plan/01-architecture.md
//     §2.2);
//   - Engine — движок валидации записей наполнения: применимость
//     параметров/атрибутов к классу записи (parameter_kinds/attribute_kinds,
//     D7), типы значений (exact/at_least/at_most/range/text/enum),
//     позитивность/allow_negative, потолок, наборы условий
//     (required/optional/запрещено, условия-константы fixed_value), enum;
//   - реестр именованных правил (year_range, cap_dimensions_form,
//     temp_pair, cap_variant_matrix, resistor_variant_power) и механизм
//     привязки правил данными (параметр/атрибут/класс записи);
//   - ApplyCatalog — применение каталога (upsert по коду) с валидацией
//     метасхемы при импорте (docs/plan/03-data-model.md §11).
//
// Каталог — данные (D1): расширение параметрами/атрибутами/условиями —
// вставкой строк, без правки кода; код решает только механику проверок.
