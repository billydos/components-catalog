package storage

import (
	"context"
	"database/sql"
	"errors"
	"strings"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib" // драйвер регистрируется как "pgx"
)

// postgresDialect — диалект PostgreSQL (pgx/v5 в режиме stdlib): единый пул
// соединений для чтения и записи (план 02 §4); параметры пула — из
// конфигурации.
type postgresDialect struct{}

func (postgresDialect) Name() string { return "postgres" }

// RewriteDDL подставляет авто-PK и точные типы: INTEGER → BIGINT —
// диапазон int64 у id и ссылок совпадает со sqlite, входные значения вне
// int4 (REST/поиск по id) не отбрасываются кодированием параметров;
// REAL → DOUBLE PRECISION — sqlite REAL хранит float64, postgres REAL —
// float4 (бит-точное сравнение состояний повторного импорта расползалось
// бы на четвёртом знаке).
func (postgresDialect) RewriteDDL(stmt string) string {
	return strings.NewReplacer(
		"INTEGER", "BIGINT",
		"REAL", "DOUBLE PRECISION",
		autoIncToken, "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
	).Replace(stmt)
}

func (postgresDialect) InsertReturningID(ctx context.Context, tx *sql.Tx, query string, args []any) (int64, error) {
	var id int64
	if err := tx.QueryRowContext(ctx, query+" RETURNING id", args...).Scan(&id); err != nil {
		return 0, err
	}
	return id, nil
}

func (postgresDialect) InsertIfAbsentReturningID(ctx context.Context, tx *sql.Tx, query string, args []any) (int64, bool, error) {
	var id int64
	err := tx.QueryRowContext(ctx, query+" ON CONFLICT DO NOTHING RETURNING id", args...).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, false, nil
	}
	if err != nil {
		return 0, false, err
	}
	return id, true, nil
}

// appendDSNParam дописывает параметр к DSN в его форме: URL
// (postgres://…) — в строку запроса, ключевая (host=… port=…) — через
// пробел. pgx передаёт неизвестные ему параметры серверу в стартовом
// пакете — значение действует на каждое соединение пула без
// дополнительного round-trip.
func appendDSNParam(dsn, param string) string {
	if strings.Contains(dsn, "://") {
		sep := "?"
		if strings.Contains(dsn, "?") {
			sep = "&"
		}
		return dsn + sep + param
	}
	return dsn + " " + param
}

// withJitDisabled дописывает к DSN runtime-параметр jit=off, если jit
// не задан явно (docs/plan/02-database.md §4). Нагрузка модуля — короткие
// точечные запросы; оценка стоимости плана параметрического поиска,
// раздутая коррелированными EXISTS вариантной семантики, переваливает за
// jit_threshold (100 тыс.), и LLVM-компиляция стоит на слабых CPU сотни
// мс при десятках мс выполнения (измерения — qa/reports). Явно заданный
// jit= (ключ параметра DSN, а не подстрока пароля) не перекрывается.
func withJitDisabled(dsn string) string {
	if dsnJitSet(dsn) {
		return dsn
	}
	return appendDSNParam(dsn, "jit=off")
}

// dsnSpaces — разделители пар ключевой формы DSN (как в разборе pgx).
const dsnSpaces = " \t\n\r\v\f"

func isDsnSpace(c byte) bool { return strings.IndexByte(dsnSpaces, c) >= 0 }

// dsnJitSet сообщает, задан ли jit= в DSN явно — как параметр, а не
// подстрока учётных данных. URL-форма: ключ строки запроса — сразу после
// «?» или «&». Ключевая форма: имя пары «ключ=значение» по правилам
// разбора pgx (пробелы вокруг «=» допускаются; пробелы внутри значения —
// только в кавычках '…' или после экранирующего «\» — там границы ключа
// не возникает).
func dsnJitSet(dsn string) bool {
	if strings.Contains(dsn, "://") {
		return strings.Contains(dsn, "?jit=") || strings.Contains(dsn, "&jit=")
	}
	s := strings.TrimLeft(dsn, dsnSpaces)
	for len(s) > 0 {
		eq := strings.IndexByte(s, '=')
		if eq < 0 {
			return false
		}
		if key := strings.TrimRight(s[:eq], dsnSpaces); key == "jit" {
			return true
		}
		s = strings.TrimLeft(s[eq+1:], dsnSpaces)
		if len(s) == 0 {
			return false
		}
		if s[0] == '\'' {
			s = skipQuotedValue(s[1:])
		} else {
			s = skipUnquotedValue(s)
		}
		s = strings.TrimLeft(s, dsnSpaces)
	}
	return false
}

// skipUnquotedValue пропускает незакавыченное значение ключевой формы
// (до разделителя-пробела; «\» экранирует следующий символ, включая
// пробел).
func skipUnquotedValue(s string) string {
	for len(s) > 0 && !isDsnSpace(s[0]) {
		if s[0] == '\\' && len(s) > 1 {
			s = s[2:]
			continue
		}
		s = s[1:]
	}
	return s
}

// skipQuotedValue пропускает закавыченное значение до закрывающей
// кавычки («\» экранирует); незакрытая кавычка — до конца строки (такой
// DSN всё равно отвергается драйвером при разборе).
func skipQuotedValue(s string) string {
	for len(s) > 0 {
		if s[0] == '\\' && len(s) > 1 {
			s = s[2:]
			continue
		}
		c := s[0]
		s = s[1:]
		if c == '\'' {
			break
		}
	}
	return s
}

func (postgresDialect) Open(ctx context.Context, cfg Config) (*pools, error) {
	db, err := sql.Open("pgx", withJitDisabled(cfg.DSN))
	if err != nil {
		return nil, err
	}
	if cfg.Pool.MaxOpen > 0 {
		db.SetMaxOpenConns(cfg.Pool.MaxOpen)
	}
	if cfg.Pool.MaxIdle > 0 {
		db.SetMaxIdleConns(cfg.Pool.MaxIdle)
	}
	if cfg.Pool.ConnMaxLifetime > 0 {
		db.SetConnMaxLifetime(durationOf(cfg.Pool.ConnMaxLifetime))
	}
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, err
	}
	return &pools{reads: db, writes: db, same: true}, nil
}

func durationOf(ns int64) time.Duration { return time.Duration(ns) * time.Nanosecond }
