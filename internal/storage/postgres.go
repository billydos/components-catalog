// postgresDialect — диалект PostgreSQL (pgx/v5 в режиме stdlib): единый пул
// соединений для чтения и записи (план 02 §4); параметры пула — из
// конфигурации.
type postgresDialect struct{}

func (postgresDialect) Name() string { return "postgres" }

// RewriteDDL подставляет авто-PK и точные типы: INTEGER → BIGINT —
// диапазон int64 у id и ссылок совпадает со sqlite, входные значения вне
// int4 (REST/поиск по id) не отбрасываются кодированием параметров;
// REAL → DOUBLE PRECISION — sqlite REAL хранит float64, postgres REAL —
// float4 (бит-точное сравнение состояний повторного импорта расползалось
// бы на четвёртом знаке). Замена — только целые слова вне строковых
// литералов, закавыченных идентификаторов и комментариев: появление
// «INTEGER»/«REAL» внутри имени или литерала будущего DDL схему не исказит.
func (postgresDialect) RewriteDDL(stmt string) string {
	var b strings.Builder
	replaceWord := func(s, from, to string) string {
		for i := 0; i < len(s); {
			switch {
			case s[i] == '\'':
				j := skipSQLString(s, i)
				b.WriteString(s[i:j])
				i = j
			case s[i] == '"':
				j := skipSQLQuotedIdent(s, i)
				b.WriteString(s[i:j])
				i = j
			case s[i] == '-' && i+1 < len(s) && s[i+1] == '-':
				j := skipSQLLineComment(s, i)
				b.WriteString(s[i:j])
				i = j
			case s[i] == '/' && i+1 < len(s) && s[i+1] == '*':
				j := skipSQLBlockComment(s, i)
				b.WriteString(s[i:j])
				i = j
			default:
				if hasWordAt(s, i, from) {
					b.WriteString(to)
					i += len(from)
					continue
				}
				b.WriteByte(s[i])
				i++
			}
		}
		out := b.String()
		b.Reset()
		return out
	}
	return strings.NewReplacer(autoIncToken, "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").
		Replace(replaceWord(replaceWord(stmt, "INTEGER", "BIGINT"), "REAL", "DOUBLE PRECISION"))
}

// hasWordAt сообщает, начинается ли в s целое слово word с позиции i:
// границы — не идентификаторные символы (превышение проверяет вызывающий).
func hasWordAt(s string, i int, word string) bool {
	if !strings.HasPrefix(s[i:], word) {
		return false
	}
	end := i + len(word)
	if i > 0 && isIdentChar(s[i-1]) {
		return false
	}
	return end >= len(s) || !isIdentChar(s[end])
}

func skipSQLString(s string, i int) int {
	j := i + 1
	for j < len(s) {
		if s[j] == '\'' {
			if j+1 < len(s) && s[j+1] == '\'' {
				j += 2
				continue
			}
			j++
			break
		}
		j++
	}
	if j > len(s) {
		return len(s)
	}
	return j
}

// skipSQLQuotedIdent пропускает закавыченный идентификатор «"…"»
// (кавычка внутри удваивается); незакрытый — до конца строки.
func skipSQLQuotedIdent(s string, i int) int {
	j := i + 1
	for j < len(s) {
		if s[j] == '"' {
			if j+1 < len(s) && s[j+1] == '"' {
				j += 2
				continue
			}
			j++
			break
		}
		j++
	}
	if j > len(s) {
		return len(s)
	}
	return j
}

func skipSQLLineComment(s string, i int) int {
	if j := strings.IndexByte(s[i:], '\n'); j >= 0 {
		return i + j + 1
	}
	return len(s)
}

func skipSQLBlockComment(s string, i int) int {
	if j := strings.Index(s[i+2:], "*/"); j >= 0 {
		return i + j + 4
	}
	return len(s)
}

func (postgresDialect) InsertReturningID(ctx context.Context, tx *sql.Tx, query string, args []any) (int64, error) {
	var id int64
	if err := tx.QueryRowContext(ctx, query+" RETURNING id", args...).Scan(&id); err != nil {
		return 0, err
	}
	return id, nil
}

func (postgresDialect) InsertIfAbsentReturningID(ctx context.Context, tx *sql.Tx, query string, args []any) (int64, bool, error) {
	var id int64
	err := tx.QueryRowContext(ctx, withOnConflict(query)+" RETURNING id", args...).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, false, nil
	}
	if err != nil {
		return 0, false, err
	}
	return id, true, nil
}

// appendDSNParam дописывает параметр к DSN в его форме: URL
// (postgres://…) — в строку запроса через net/url (позиция после
// фрагмента и специальные символы учтены разбором, а не конкатенацией),
// ключевая (host=… port=…) — через пробел. pgx передаёт неизвестные ему
// параметры серверу в стартовом пакете — значение действует на каждое
// соединение пула без дополнительного round-trip.
func appendDSNParam(dsn, param string) string {
	if strings.Contains(dsn, "://") {
		if u, err := url.Parse(dsn); err == nil {
			// Порядок существующих параметров сохраняется (RawQuery
			// дописывается, а не пересобирается), параметр встаёт до
			// фрагмента — разбор net/url, а не конкатенация.
			if u.RawQuery == "" {
				u.RawQuery = param
			} else {
				u.RawQuery += "&" + param
			}
			return u.String()
		}
		if strings.Contains(dsn, "?") {
			return dsn + "&" + param
		}
		return dsn + "?" + param
	}
	return dsn + " " + param
}

// withJitDisabled дописывает к DSN runtime-параметр jit=off, если jit
// не задан явно (docs/plan/02-database.md §4). Нагрузка модуля — короткие
// точечные запросы; оценка стоимости плана параметрического поиска,
// раздутая коррелированными EXISTS вариантной семантики, переваливает за
// jit_threshold (100 тыс.), и LLVM-компиляция стоит на слабых CPU сотни
// мс при десятках мс выполнения (измерения — qa/reports). Явно заданный
// jit= (ключ параметра DSN, а не подстрока пароля) не перекрывается.
func withJitDisabled(dsn string) string {
	if dsnJitSet(dsn) {
		return dsn
	}
	return appendDSNParam(dsn, "jit=off")
}

// dsnSpaces — разделители пар ключевой формы DSN (как в разборе pgx).
const dsnSpaces = " \t\n\r\v\f"

func isDsnSpace(c byte) bool { return strings.IndexByte(dsnSpaces, c) >= 0 }

// dsnJitSet сообщает, задан ли jit= в DSN явно — как параметр, а не
// подстрока учётных данных. URL-форма разбирается net/url: ключи строки
// запроса, а не подстроки пароля userinfo. Ключевая форма: имя пары
// «ключ=значение» по правилам разбора pgx (пробелы вокруг «=» допускаются;
// пробелы внутри значения — только в кавычках '…' или после экранирующего
// «\» — там границы ключа не возникает).
func dsnJitSet(dsn string) bool {
	if strings.Contains(dsn, "://") {
		if u, err := url.Parse(dsn); err == nil {
			_, ok := u.Query()["jit"]
			return ok
		}
		return true // неразбираемый URL не достраивается параметром
	}
	s := strings.TrimLeft(dsn, dsnSpaces)
	for len(s) > 0 {
		eq := strings.IndexByte(s, '=')
		if eq < 0 {
			return false
		}
		if key := strings.TrimRight(s[:eq], dsnSpaces); key == "jit" {
			return true
		}
		s = strings.TrimLeft(s[eq+1:], dsnSpaces)
		if len(s) == 0 {
			return false
		}
		if s[0] == '\'' {
			s = skipQuotedValue(s[1:], '\'')
		} else {
			s = skipUnquotedValue(s)
		}
		s = strings.TrimLeft(s, dsnSpaces)
	}
	return false
}

// skipUnquotedValue пропускает незакавыченное значение ключевой формы
// (до разделителя-пробела; «\» экранирует следующий символ, включая
// пробел).
func skipUnquotedValue(s string) string {
	for len(s) > 0 && !isDsnSpace(s[0]) {
		if s[0] == '\\' && len(s) > 1 {
			s = s[2:]
			continue
		}
		s = s[1:]
	}
	return s
}

// skipQuotedValue пропускает закавыченное значение до закрывающей
// кавычки quote («\» экранирует); незакрытая кавычка — до конца строки
// (такой DSN всё равно отвергается драйвером при разборе).
func skipQuotedValue(s string, quote byte) string {
	for len(s) > 0 {
		if s[0] == '\\' && len(s) > 1 {
			s = s[2:]
			continue
		}
		c := s[0]
		s = s[1:]
		if c == quote {
			break
		}
	}
	return s
}

func (postgresDialect) Open(ctx context.Context, cfg Config) (*pools, error) {
	db, err := sql.Open("pgx", withJitDisabled(cfg.DSN))
	if err != nil {
		return nil, err
	}
	if cfg.Pool.MaxOpen > 0 {
		db.SetMaxOpenConns(cfg.Pool.MaxOpen)
	}
	if cfg.Pool.MaxIdle > 0 {
		db.SetMaxIdleConns(cfg.Pool.MaxIdle)
	}
	if cfg.Pool.ConnMaxLifetime > 0 {
		db.SetConnMaxLifetime(durationOf(cfg.Pool.ConnMaxLifetime))
	}
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, err
	}
	return &pools{reads: db, writes: db, same: true}, nil
}

func durationOf(ns int64) time.Duration { return time.Duration(ns) * time.Nanosecond }
