// Package i18n — бандлы отображаемых строк каталога (решение D9,
// docs/plan/01-architecture.md §2.6). База и формат наполнения
// языконезависимы: каталожные таблицы хранят только коды и структурные
// метаданные; отображаемые названия классов, систем обозначений, семейств,
// единиц (имя и символ), условий, групп, параметров, атрибутов, описания
// правил и имена полей разбора живут здесь.
//
// Канонический язык — en: его словарь полон для всех кодов сидов (пин-тест
// seed/seed_test.go); ru — полный словарь локализации. Разрешение строки:
// запрошенная локаль → en → сам код сущности (последняя инстанция для
// расширений каталога данными, у которых нет записи в бандлах).
//
// Пакет зависит только от кодов-строк (без внутренних слоёв); потребители
// локализованного рендера — транспорты (httpapi, cli) и тесты полноты.
// Локали не проникают в domain/catalog/storage/service. Исключение —
// locale-нейтральное ядро рендера (Canonical, Arg): domain использует его
// для канонического en-рендера Error.Message (план 01 §1, §2.6).
